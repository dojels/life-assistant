# -- 人设(顺序固定:IDENTITY 在它上面,运行时上下文在它下面)------------------
#
# ⭐ 为什么人设块放在**中间**:runtime 每轮都变,IDENTITY 与人设都是静态文本。
#    把静态的放前面,前缀缓存的命中段就更长(web/memory_view.py 里那句
#    "顺序稳定,为了 KV 缓存命中"说的就是这个)。
#
# ⚠️ 人设块**不许**塞硬约束。D47 的结论是"红线写进返回值,不写在提示词里" ——
#    医疗免责、误差区间、脱敏占位符都由领域层的返回结构负责,提示词只管道词造句。
#    这里写死的只有一件事:**优先级**(事实 > 边界 > 任务 > 性情)。

# ⭐ 2026-10-13 起人设分**两半**(见 D117,人格页 /persona 能改的就是上半段):
#    * PERSONA_BODY —— 「性情与口吻」,用户可改。它是**数据**(存在 sys_settings 里),
#      这里这份只是**出厂默认**;
#    * PERSONA_TAIL —— 优先级阶梯,由代码**无条件追加**,页面上不可编辑。
#    为什么红线只留这一段却不许改:"人设只影响怎么说,不影响说什么"是这个实验的
#    安全绳(改丢了它,人格就会开始软化坏消息、回避该问的问题)—— 红线靠结构,不靠自觉(D47)。
