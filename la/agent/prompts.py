PERSONA = PERSONA_BODY + "\n\n" + PERSONA_TAIL


def build_persona_text(body: str | None = None) -> str:
    """拼出这一轮真正给模型的人设块:**用户写的主体 + 代码固定的尾巴**。

    ⚠️ 尾巴不受 body 影响 —— 哪怕主体里一个字都没提优先级,它也在。
       这是故意的:用户能改的是"她像谁",不是"她能不能为了讨好人而不说实话"。
    """
    text = (PERSONA_BODY if body is None else str(body)).strip()
    return (text + "\n\n" + PERSONA_TAIL) if text else PERSONA_TAIL


# -- 对话入口 ---------------------------------------------------------------
#
# ⭐ 模型必须知道这句话是从哪来的。同一句"把本周小结整理一下":
#     在电脑上 → 可以甩一张 Markdown 表格,可以让他"打开素材页第三张照片";
#     在微信里 → 手机上表格会挤成一行、压根没有"素材页"这个页面可点。
# 不知道入口的模型会默认按电脑那套说话,于是手机用户拿到一串没法看的东西。
#
# ⚠️ 这是**运行时事实**,由代码按渠道注入,不是让模型从上下文里猜。
SURFACE_WEIXIN = "weixin"
SURFACE_WEB = "web"
SURFACE_CLI = "cli"

#: 入口 -> (给模型看的名字, 这个入口下的行为约束)
SURFACES: dict[str, tuple[str, str]] = {
    SURFACE_WEIXIN: (
        "手机微信(聊天窗口)",
        "回复要短,一屏能看完;不要用 Markdown 表格(微信里会挤成一坨);"
        "不要让他「打开某个页面看一下」—— 他手上只有微信;"
        "要交付文件就直接用 artifact_write 生成,系统会把文件发给他"
        "(要做网页就用 html_page:它生成的 .html 会作为**文件**发过去,"
        "他在手机上点开就是浏览器里的页面;别让他去点网页版才有的「预览」)。",
    ),
    SURFACE_WEB: (
        "电脑网页",
        "可以用 Markdown 表格与较长内容;需要他查看素材或产物时,可以让他打开对应页面。",
    ),
    SURFACE_CLI: (
        "电脑终端",
        "纯文本,不要用 Markdown 表格;可以直接告诉他文件在磁盘上的路径。",
    ),
}


#: 渠道名 -> 入口名。桥接层直接拿 Inbound.channel 当入口,所以要收敛同义词
#: (终端适配器的渠道名是 console,而入口叫 cli)。
SURFACE_ALIASES = {"console": SURFACE_CLI, "terminal": SURFACE_CLI, "stdin": SURFACE_CLI}


def surface_lines(surface: str) -> list[str]:
    """把入口翻成给模型看的那两行。**认不出的入口照原样报,绝不猜**。"""
    key = str(surface or "").strip()
    if not key:
        return []
    key = SURFACE_ALIASES.get(key, key)
    known = SURFACES.get(key)
    if known is None:
        return ["对话入口: " + key]
    return ["对话入口: " + known[0], "入口约束: " + known[1]]


def build_runtime_context(
    settings: Settings,
    *,
    turn: int = 1,
    last_active: str | None = None,
    surface: str = "",
    session_id: str | None = None,
) -> str:
    """运行时上下文:每轮都必须由代码生成并注入,不能靠模型猜时间。

    ⚠️ session_id 必须由**会话**给(2026-10-18 审计修):Web/微信的真实会话是
       member:<id> / bridge:<id>,而 settings.session_id 只来自 LA_SESSION_ID。
       以前一律用后者,模型被告知的是一个并不存在的会话。
    """
    moment = settings.now()
    lines = [
        "<runtime-context>",
        "当前时间: " + format_local(moment),
        "时区: " + settings.timezone,
        "会话: " + str(session_id or settings.session_id),
        "本轮序号: " + str(turn),
    ]
    lines.extend(surface_lines(surface))
    if last_active:
        lines.append("上次活动: " + last_active)
    lines.append("</runtime-context>")
    return "\n".join(lines)


def build_system_message(
    settings: Settings,
    *,
    turn: int = 1,
    last_active: str | None = None,
    surface: str = "",
    persona: str | None = None,
) -> dict[str, str]:
    """身份 → 人设 → 运行时上下文。

    ⭐ `persona` 是**用户自己写的那半段**(人格页 /persona 保存的);不传就用出厂默认。
       固定尾巴由 build_persona_text 无条件补上 —— 调用方不需要(也不许)自己拼。
    """
    content = IDENTITY + "\n\n" + build_persona_text(persona) + "\n\n" + build_runtime_context(
        settings, turn=turn, last_active=last_active, surface=surface
    )
    return {"role": "system", "content": content}
